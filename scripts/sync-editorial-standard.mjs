import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(repo, 'packages/core/src/pptd/editorial-standard.json');
const raw = await fs.readFile(source, 'utf8');
const standard = JSON.parse(raw);
if (
  standard.schemaVersion !== 1 ||
  !Array.isArray(standard.rules) ||
  !Array.isArray(standard.stages)
)
  throw new Error('Invalid canonical editorial standard.');
const ids = new Set();
for (const rule of standard.rules) {
  if (!/^[A-Z]+(?:-[A-Z]+)*-[0-9]{2}$/.test(rule.id) || ids.has(rule.id))
    throw new Error('Duplicate/invalid editorial rule ID.');
  if (!['hard', 'advisory', 'visual'].includes(rule.level) || !rule.avoid || !rule.prefer)
    throw new Error('Missing rule level, anti-pattern, or preferred behavior: ' + rule.id);
  ids.add(rule.id);
}
const sha = createHash('sha256').update(raw).digest('hex');
const sections = [
  '# HUANDENG Editorial Standard — generated from one canonical registry',
  '',
  '<!-- GENERATED. Do not edit this file; edit packages/core/src/pptd/editorial-standard.json and run pnpm sync:editorial. -->',
  '',
  'Version: ' + standard.version + ' · Source SHA-256: ' + sha,
  '',
  standard.principle,
  '',
  'Rules are not a blanket prohibition on arrows, cards, colors or sparse pages. Check the communicative function and the approved Project style. Only machine-verifiable defects can be mechanically blocked; aesthetic judgment requires actual rendered review.',
  '',
  '## Unified authoring pipeline',
  '',
];
for (const stage of standard.stages) {
  sections.push('### ' + stage.id, '');
  for (const item of stage.requires) sections.push('- ' + item);
  sections.push('');
}
for (const kind of ['hard', 'advisory', 'visual']) {
  sections.push('## ' + kind.toUpperCase() + ' rules', '');
  for (const rule of standard.rules.filter((item) => item.level === kind)) {
    sections.push(
      '### ' + rule.id + ' · ' + rule.title,
      '',
      '**Avoid:** ' + rule.avoid,
      '',
      '**Prefer:** ' + rule.prefer,
      '',
    );
  }
}
sections.push(
  '## Required agent output and honesty',
  '',
  '- Before a substantial new deck, prototype and render 2–3 unlike pages (evidence, comparison, process) before scaling.',
  '- Invoke the live huandeng_design_audit or quality CLI after implementation, fix actionable findings, and re-run.',
  '- For a reproducible machine-readable final gate, use huandeng_authoring_gate or CLI quality --gate (if advertised by the active runtime). A pass covers deterministic checks only; it never substitutes for actual image inspection.',
  '- Provide the exact Page IDs reviewed and say whether renders were actually viewed. Do not manufacture evidence or mark an audit as passed without invoking it.',
  '- Keep delivery diagnostics, safety/provenance audit and AI self-congratulation off the presentation unless the audience needs them.',
  '- Preserve the user’s original claims, data labels, original images and explicit exceptions.',
  '',
);
const markdown = sections.join('\n');
const targets = [
  {
    file: path.join(
      repo,
      'plugins/huandeng/skills/huandeng-story/references/editorial-standard.md',
    ),
    content: markdown,
  },
  {
    file: path.join(repo, 'packages/core/src/pptd/editorial-guide.generated.json'),
    content:
      JSON.stringify({ version: standard.version, sourceSha256: sha, text: markdown }, null, 2) +
      '\n',
  },
];
const checking = process.argv.includes('--check');
let drift = 0;
for (const target of targets) {
  const old = await fs.readFile(target.file, 'utf8').catch(() => null);
  if (old === target.content) continue;
  if (checking) {
    console.error('Editorial generated file drift:', path.relative(repo, target.file));
    drift += 1;
  } else {
    await fs.mkdir(path.dirname(target.file), { recursive: true });
    await fs.writeFile(target.file, target.content);
    console.log('Generated:', path.relative(repo, target.file));
  }
}
if (drift) process.exitCode = 1;
else console.log('Editorial standard verified:', standard.version, sha.slice(0, 12));
