async function probe(file, expectedFrames) {
  const { stdout } = await execute(
    ffprobe,
    ['-v', 'error', '-count_frames', '-show_streams', '-show_format', '-of', 'json', file],
    { timeout: 60000, maxBuffer: 4 * 1024 * 1024, windowsHide: true },
  );
  const data = JSON.parse(stdout);
  const stream = data.streams.find((item) => item.codec_type === 'video');
  assert.equal(stream.codec_name, 'h264');
  assert.equal(stream.pix_fmt, 'yuv420p');
  assert.equal(stream.width, 1280);
  assert.equal(stream.height, 720);
  assert.equal(stream.avg_frame_rate, '24/1');
  assert.equal(Number(stream.nb_read_frames), expectedFrames);
  assert.ok(Math.abs(Number(data.format.duration) - expectedFrames / 24) < 0.03);
  assert.equal(
    data.streams.some((item) => item.codec_type === 'audio'),
    false,
  );
  return {
    width: stream.width,
    height: stream.height,
    codec: stream.codec_name,
    fps: stream.avg_frame_rate,
    frames: Number(stream.nb_read_frames),
    seconds: Number(data.format.duration),
    audio: false,
  };
}
function centroid(bytes, color = 'red') {
  let count = 0;
  let x = 0;
  let y = 0;
  for (let offset = 0; offset < bytes.length; offset += 3) {
    const [r, g, b] = bytes.subarray(offset, offset + 3);
    const match = color === 'red' ? r > 160 && g < 100 && b < 100 : b > 160 && r < 100 && g < 130;
    if (!match) continue;
    const pixel = offset / 3;
    count++;
    x += pixel % 1280;
    y += Math.floor(pixel / 1280);
  }
  assert.ok(count > 10000, `Expected a visible ${color} rectangle, found ${count} pixels.`);
  return { x: x / count, y: y / count, pixels: count };
}
async function frames(file, indices, name, colors = []) {
  const filter = `select=${indices.map((index) => `eq(n\\,${index})`).join('+')}`;
  const { stdout } = await execute(
    ffmpeg,
    [
      '-hide_banner',
      '-loglevel',
      'error',
      '-i',
      file,
      '-vf',
      filter,
      '-vsync',
      '0',
      '-f',
      'rawvideo',
      '-pix_fmt',
      'rgb24',
      'pipe:1',
    ],
    { timeout: 60000, encoding: 'buffer', maxBuffer: 64 * 1024 * 1024, windowsHide: true },
  );
  const bytesPerFrame = 1280 * 720 * 3;
  assert.equal(stdout.length, bytesPerFrame * indices.length);
  const measurements = indices.map((frame, index) => ({
    frame,
    ...centroid(
      stdout.subarray(index * bytesPerFrame, (index + 1) * bytesPerFrame),
      colors[index] ?? 'red',
    ),
  }));
  for (const frame of indices) {
    await execute(
      ffmpeg,
      [
        '-hide_banner',
        '-loglevel',
        'error',
        '-i',
        file,
        '-vf',
        `select=eq(n\\,${frame})`,
        '-frames:v',
        '1',
        '-y',
        path.join(evidence, `${name}-frame-${frame}.png`),
      ],
      { timeout: 60000, maxBuffer: 4 * 1024 * 1024, windowsHide: true },
    );
  }
  return measurements;
}
