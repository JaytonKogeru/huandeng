async function api(route, body, expectedStatus) {
  const response = await fetch(`${serviceUrl}/__pptd${route}`, {
    method: body === undefined ? 'GET' : 'POST',
    headers: { 'content-type': 'application/json', 'x-huandeng-token': sessionToken },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    signal: AbortSignal.timeout(120000),
  });
  const text = await response.text();
  let result;
  try {
    result = JSON.parse(text);
  } catch {
    result = { message: text };
  }
  if (expectedStatus !== undefined) assert.equal(response.status, expectedStatus, text);
  else assert.ok(response.ok && result.ok !== false, `${route}: ${text}`);
  return result;
}
async function freePort() {
  const listener = createServer();
  await new Promise((resolve, reject) => {
    listener.once('error', reject);
    listener.listen(0, '127.0.0.1', resolve);
  });
  const port = listener.address().port;
  await new Promise((resolve, reject) =>
    listener.close((error) => (error ? reject(error) : resolve())),
  );
  return port;
}
function logProcess(process, label) {
  process.stdout?.on('data', (data) => processLog.push(`${label} stdout: ${String(data)}`));
  process.stderr?.on('data', (data) => processLog.push(`${label} stderr: ${String(data)}`));
  launchExit = new Promise((resolve) =>
    process.once('exit', (code, signal) => resolve({ label, code, signal })),
  );
}
