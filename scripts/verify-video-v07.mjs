async function closeNormally() {
  const exit = launchExit;
  if (application) {
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  } else {
    await browser?.close();
    browser = undefined;
    child.send({ type: 'huandeng:shutdown' });
  }
  let timer;
  let result;
  try {
    result = await Promise.race([
      exit,
      new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error('Candidate did not close normally.')), 30000);
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
  exits.push(result);
  assert.equal(result.code, 0);
  assert.equal(result.signal, null);
  application = undefined;
  child = undefined;
  page = undefined;
  const remaining = await fs.readdir(path.join(runtime, 'export-jobs')).catch(() => []);
  assert.deepEqual(remaining, [], 'Closing the project must remove its job directories.');
  return result;
}
