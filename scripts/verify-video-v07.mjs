async function eventually(work, timeout = 120000, interval = 100) {
  const deadline = Date.now() + timeout;
  let last;
  while (Date.now() < deadline) {
    try {
      const result = await work();
      if (result) return result;
    } catch (error) {
      last = error;
    }
    await delay(interval);
  }
  throw last ?? new Error('Timed out waiting for acceptance condition.');
}
